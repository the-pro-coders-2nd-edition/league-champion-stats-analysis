def _block_third_party_cdns(route: Any) -> None:
    """Abort requests to the two CDNs `index.html` hardcodes (Plotly, Iconify).

    Both render asynchronously after the page's own render-complete signal fires (Plotly builds
    real SVG chart DOM well after ``fetchBuild`` resolves), so leaving them reachable makes the
    snapshot's element count and structure a function of network timing -- exactly the kind of
    flakiness this test must not have. `PlotlyFigure.svelte` sets the container's `innerHTML`
    directly from the payload (see its module docstring), so the structural DOM (a wrapper div
    plus an empty `.plotly-graph-div`) is fully deterministic without the library ever loading;
    only pixel-level chart rendering is lost, which this test never asserts on anyway.
    """
    route.abort()


