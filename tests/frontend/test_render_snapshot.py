SVELTE_HASH_RE = re.compile(r"^svelte-[a-z0-9]+$")

_CAPTURE_JS = """
([scopeSelector, prefixes, properties]) => {
  const root = document.querySelector(scopeSelector);
  if (!root) return null;
  const svelteHashRe = /^svelte-[a-z0-9]+$/;
  const all = Array.from(root.querySelectorAll('*'));
  const occurrence = {};
  const elements = [];
  const watched = [];
  const classSet = new Set();
  for (const el of all) {
    const tag = el.tagName.toLowerCase();
    const classes = Array.from(el.classList)
      .filter((c) => !svelteHashRe.test(c))
      .sort();
    classes.forEach((c) => classSet.add(c));
    const key = tag + '.' + classes.join('.');
    occurrence[key] = (occurrence[key] || 0) + 1;
    const selector = classes.length ? `${tag}.${classes.join('.')}` : tag;
    const identity = `${selector} (#${occurrence[key]})`;
    elements.push({ identity, tag, classes });
    const isWatched = classes.some((c) => prefixes.some((p) => c.startsWith(p)));
    if (isWatched) {
      const style = window.getComputedStyle(el);
      const styles = {};
      for (const prop of properties) styles[prop] = style.getPropertyValue(prop);
      watched.push({ identity, tag, classes, styles });
    }
  }
  return { elements, watched, class_set: Array.from(classSet).sort() };
}
"""

_DISABLE_ANIMATIONS_INIT_SCRIPT = """
(() => {
  const inject = () => {
    if (!document.documentElement) {
      requestAnimationFrame(inject);
      return;
    }
    const style = document.createElement('style');
    style.id = '__pw_disable_animations__';
    style.textContent = `
      *, *::before, *::after {
        animation: none !important;
        transition: none !important;
        scroll-behavior: auto !important;
      }
    `;
    document.documentElement.appendChild(style);
  };
  inject();
})();
"""


def _free_port() -> int:
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as sock:
        sock.bind(("127.0.0.1", 0))
        return sock.getsockname()[1]


def _wait_for_server(base_url: str, timeout_s: float = 10.0) -> None:
    """Poll server startup readiness. Infra bring-up, not a page-render wait."""
    deadline = time.monotonic() + timeout_s
    last_error: Exception | None = None
    while time.monotonic() < deadline:
        try:
            with urllib.request.urlopen(f"{base_url}/health", timeout=0.5) as response:
                if response.status == 200:
                    return
        except (urllib.error.URLError, ConnectionError, OSError) as exc:
            last_error = exc
            time.sleep(0.05)
    raise RuntimeError(f"server did not become ready at {base_url}") from last_error


