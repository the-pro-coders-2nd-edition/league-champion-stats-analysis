"""DOM + computed-style snapshot test for the Svelte report SPA (RFC-001, guardrail step 1).

This is "the only oracle this migration has" (RFC-001, migration step 1): there is no visual
regression testing today, so this test serves a committed, realistic ``report.json`` fixture through
the real FastAPI app, drives the built SPA with a real Chromium via Playwright, and for each of the
six report category tabs at two viewports asserts (a) every element's tag + sorted class list with
Svelte scope-hash tokens stripped, (b) ``getComputedStyle()`` for a fixed property set on every
element whose class matches a broad "interesting" prefix list, and (c) the full set of distinct class
names present in the DOM -- the only way to catch a JS string-builder emitting a class no source grep
would find (RFC-001, "A grep-based gate cannot see interpolated class emitters").

Two viewports, not one
-----------------------
>=861px (``DESKTOP_WIDTH``) and <=860px (``MOBILE_WIDTH``). RFC-001 documents a real, currently-dead
mobile override (``report.css:951-955`` / ``:404-408`` -- a ``.form-mover`` / ``.peer-driver`` mobile
rule beaten by a same-specificity scoped Svelte rule emitted later) that a single-viewport snapshot
cannot see. A change that raises a selector's specificity (e.g. un-globalling in migration step 21)
flips who wins a tie *only* at the viewport where the loser used to matter, so both viewports must be
captured every run.

Playwright dependency decision
-------------------------------
``playwright==1.47.0`` is pinned in ``pyproject.toml``'s ``dev`` dependency group (not a base runtime
dependency -- nothing in ``src/league_stats`` imports it). Pinning the pip package pins the Chromium
build it downloads (``playwright install chromium`` resolves against the installed package version),
which is the "pinned browser version" flakiness control RFC-001 asks for; floating the dependency
would silently float the browser build too. Docs "environment without Playwright" note: a
separately-provided interpreter (as used ad hoc elsewhere for manual testing) was considered and
rejected here, because this test needs to import ``playwright.sync_api`` from the *same* interpreter
that already has FastAPI/uvicorn importable to boot the app in-process -- a separate venv would need
its own copy of this whole package. Instead the test degrades gracefully (see below) in any
environment lacking the dependency or the browser binary, so a plain ``uv sync`` without
``playwright install chromium`` does not break the suite.

Graceful degradation
---------------------
``pytest.importorskip`` gates the whole module on ``playwright.sync_api`` being importable, and the
browser fixture additionally skips if launching Chromium fails (binary not installed via
``playwright install``). This matches RFC-001's characterization of this test as "required but
rerunnable": the *dedicated* CI job that runs it builds the SPA and installs Chromium first, so the
skip never fires there and the job is a required, blocking check. In the *general* ``pytest`` run
(this repo's default job, and a contributor's local ``pytest`` invocation) neither of those steps has
necessarily happened, so hard-failing here would make an unrelated Python change fail CI/local runs
for a missing frontend toolchain -- exactly the failure mode ``test_bundle_contract.py`` avoids with
its own ``skipif spa_dist absent``. The same trade-off applies one step earlier here too: this test
additionally skips if ``spa_dist`` (the built SPA, ``npm run build`` output) is absent, for the same
reason -- "required" describes the dedicated job's gate, not a hard requirement on every pytest
invocation everywhere.

Fixture recipe
--------------
``tests/frontend/fixtures/report.json`` and ``meta.json`` were generated once, committed, and are not
regenerated by this test. Recipe (see ``tests/test_reports.py`` for the helpers):

    from tests.test_reports import _make_records, _peer, _config
    from league_stats_runner.pipeline.orchestrator import run_analysis
    from league_stats_common.core.models import RankedEntry
    from league_stats_common.infra.ddragon_assets import DDragonAssets

    DDragonAssets.ensure_downloaded = lambda self, force=False: ""
    DDragonAssets.ensure_champion_ability_icons = lambda self, champion: None

    records = _make_records(40)  # 40 games -> every report section has real data, no
                                  # "insufficient data" placeholders
    peer = _peer(records)        # peer comparison populated
    ranked = RankedEntry(tier="GOLD", rank="II", league_points=45, wins=80, losses=75)
    config = _config(tmp_path, champion="Viktor", role="MIDDLE")
    run_analysis(config, records, peer_comparison=peer, ranked=ranked)
    # -> tmp_path/output/reports/test_euw/viktor_middle/{meta.json,report.json}

Serving it
----------
A real ``uvicorn`` server (not ``TestClient`` -- Playwright drives a real browser over real HTTP) is
started in a background thread on a dynamically-allocated free port (not a hardcoded fixed port,
despite the task brief's example: this suite runs under ``pytest-xdist -n auto``, so a fixed port
would collide across parallel workers). The fixture report/meta pair is copied into a temp
``WebConfig.output_dir`` before the app starts, exactly mirroring ``tests/test_web_api.py``'s
``_write_report`` shape.

Animation-disable and render-complete wait
-------------------------------------------
An init script (``BrowserContext.add_init_script``) injects a ``<style>`` forcing
``animation: none !important; transition: none !important`` onto ``document.documentElement`` as
early as the DOM allows, before the SPA's own module script runs. This is explicitly *not*
``wait_for_timeout`` (RFC-001 calls out ``deploy/compare_design.py``'s old 600/1500/6000ms constants
as the anti-pattern to avoid, and that file is deleted on the target branch). Render completion is
instead a concrete DOM signal: the loading state (``.report-loading``) is replaced by
``#report-category-tabs`` once ``fetchBuild`` resolves and Svelte renders the real content, and
switching tabs is awaited by polling for ``.report-category-panel.is-active[data-category=...]``
existing. Server-startup readiness (waiting for ``/health`` to answer before Playwright connects) is a
separate, bounded poll loop -- an infra bring-up wait, not a page-render wait, so it is not what the
RFC's warning is about.

Baselines
---------
One JSON file per (tab, viewport) under ``tests/frontend/snapshots/`` -- 12 files. Missing baselines
are written on the spot (bootstrap / first run); set ``UPDATE_SNAPSHOTS=1`` to force a rewrite on a
run where the tree is known-good. Otherwise a mismatch fails with the exact selector identity
(``tag.class1.class2 (#N)``, N being the Nth element in document order with that exact tag+class
combination) and property that changed.

Scope note for whoever integrates this after RFC-001's component-migration steps land: these
baselines were captured against *this* worktree's pre-migration ``main`` (commit ``683033f``), not
against any in-flight component rewrite happening in parallel elsewhere. They will need a full
regeneration pass (delete ``tests/frontend/snapshots/*.json``, rerun with ``UPDATE_SNAPSHOTS=1``) once
everything merges -- that is expected, not a bug in this harness.
"""

