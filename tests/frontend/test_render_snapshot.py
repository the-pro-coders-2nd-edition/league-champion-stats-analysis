def _select_tab(page: Any, tab: str) -> None:
    if tab != "summary":
        page.click(f'#report-category-tabs button[data-category="{tab}"]')
    page.wait_for_selector(
        f'.report-category-panel.is-active[data-category="{tab}"]', state="attached", timeout=15000
    )


def _capture(page: Any, tab: str) -> dict[str, Any]:
    scope_selector = f'.report-category-panel[data-category="{tab}"]'
    result = page.evaluate(_CAPTURE_JS, [scope_selector, WATCHED_CLASS_PREFIXES, WATCHED_PROPERTIES])
    assert result is not None, f"panel for tab {tab!r} not found in the DOM"
    return result


def _baseline_path(tab: str, viewport_name: str) -> Path:
    return SNAPSHOTS_DIR / f"{tab}_{viewport_name}.json"


def _diff_snapshots(baseline: dict[str, Any], current: dict[str, Any]) -> list[str]:
    diffs: list[str] = []

    base_elements = baseline.get("elements", [])
    cur_elements = current.get("elements", [])
    if len(base_elements) != len(cur_elements):
        diffs.append(
            f"element count changed: baseline had {len(base_elements)}, now {len(cur_elements)}"
        )
    for index, (base_el, cur_el) in enumerate(zip(base_elements, cur_elements)):
        if base_el["tag"] != cur_el["tag"] or base_el["classes"] != cur_el["classes"]:
            diffs.append(
                f"element #{index} changed: {base_el['tag']}.{'.'.join(base_el['classes'])} "
                f"-> {cur_el['tag']}.{'.'.join(cur_el['classes'])}"
            )

    base_classes = set(baseline.get("class_set", []))
    cur_classes = set(current.get("class_set", []))
    added = sorted(cur_classes - base_classes)
    removed = sorted(base_classes - cur_classes)
    if added:
        diffs.append(f"new class names present in the DOM (no source grep would catch these): {added}")
    if removed:
        diffs.append(f"class names no longer present in the DOM: {removed}")

    base_watched = {entry["identity"]: entry for entry in baseline.get("watched", [])}
    cur_watched = {entry["identity"]: entry for entry in current.get("watched", [])}
    for identity in sorted(set(base_watched) - set(cur_watched)):
        diffs.append(f"watched element disappeared: {identity}")
    for identity in sorted(set(cur_watched) - set(base_watched)):
        diffs.append(f"new watched element appeared: {identity}")
    for identity in sorted(set(base_watched) & set(cur_watched)):
        base_styles = base_watched[identity]["styles"]
        cur_styles = cur_watched[identity]["styles"]
        for prop, base_value in base_styles.items():
            cur_value = cur_styles.get(prop)
            if base_value != cur_value:
                diffs.append(f"{identity}: {prop} changed from {base_value!r} to {cur_value!r}")

    return diffs


def _assert_matches_baseline(tab: str, viewport_name: str, captured: dict[str, Any]) -> None:
    SNAPSHOTS_DIR.mkdir(parents=True, exist_ok=True)
    path = _baseline_path(tab, viewport_name)
    update = os.environ.get("UPDATE_SNAPSHOTS") == "1"

    if update or not path.is_file():
        path.write_text(json.dumps(captured, indent=2, sort_keys=True) + "\n", encoding="utf-8")
        return

    baseline = json.loads(path.read_text(encoding="utf-8"))
    diffs = _diff_snapshots(baseline, captured)
    if diffs:
        message = "\n".join(
            [f"render snapshot mismatch for tab={tab!r} viewport={viewport_name!r}:"]
            + [f"  - {line}" for line in diffs]
            + ["", f"If this is an intentional change, rerun with UPDATE_SNAPSHOTS=1 to accept it."]
        )
        pytest.fail(message)


@pytest.mark.parametrize("tab", TABS)
@pytest.mark.parametrize("viewport_name", list(VIEWPORTS_BY_NAME), indirect=True)
def test_render_snapshot(report_page: Any, tab: str, viewport_name: str) -> None:
    """Snapshot one report category tab at one viewport against its committed baseline."""
    _select_tab(report_page, tab)
    captured = _capture(report_page, tab)
    _assert_matches_baseline(tab, viewport_name, captured)


